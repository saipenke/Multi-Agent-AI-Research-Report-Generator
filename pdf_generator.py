def _clean_markdown(md_text: str) -> str:
    """Remove stray code fences the LLM sometimes wraps around the whole report."""
    md_text = md_text.strip()
    md_text = re.sub(r"^```(?:markdown|md)?\s*\n", "", md_text)
    md_text = re.sub(r"\n```\s*$", "", md_text)
    return md_text.strip()


def _split_title(md_text: str, fallback: str):
    m = re.match(r"\s*#\s+(.+)", md_text)
    if m:
        return m.group(1).strip(), md_text[m.end():].lstrip()
    return fallback, md_text


def build_html(md_text: str, topic: str, fallback_mode: bool = False) -> str:
    md_text = _clean_markdown(md_text)
    title, body_md = _split_title(md_text, topic.title())
    body_html = markdown.markdown(
        body_md, extensions=["tables", "fenced_code", "sane_lists"]
    )
    date_str = datetime.now().strftime("%B %d, %Y")
    css = FALLBACK_CSS if fallback_mode else WEASY_CSS
    footer = (
        '<div id="footerContent" style="font-size:8pt;color:#64748b;text-align:right;">'
        "Page <pdf:pagenumber></div>"
        if fallback_mode
        else ""
    )
    return f"""<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>{title}</title>
<style>{css}</style></head>
<body>
  <div class="cover">
    <div class="tag">Research Report</div>
    <h1>{title}</h1>
    <div class="subtitle">In-depth analysis and key findings</div>
    <div class="meta">Date: {date_str}<br>Author: {SYSTEM_TAG}</div>
  </div>
  {footer}
  {body_html}
</body></html>"""


def generate_pdf(md_text: str, topic: str):
    """Return (pdf_bytes, engine_name)."""
    # 1) Preferred: WeasyPrint
    try:
        from weasyprint import HTML

        html = build_html(md_text, topic, fallback_mode=False)
        pdf_bytes = HTML(string=html).write_pdf()
        return pdf_bytes, "WeasyPrint"
    except (OSError, ImportError, Exception) as weasy_err:  # noqa: BLE001
        weasy_error = weasy_err

    # 2) Fallback: xhtml2pdf (pure Python, works everywhere)
    try:
        from xhtml2pdf import pisa

        html = build_html(md_text, topic, fallback_mode=True)
        buffer = io.BytesIO()
        result = pisa.CreatePDF(src=html, dest=buffer)
        if result.err:
            raise RuntimeError("xhtml2pdf reported errors while building the PDF.")
        return buffer.getvalue(), "xhtml2pdf (fallback)"
    except Exception as fb_err:  # noqa: BLE001
        raise RuntimeError(
            f"PDF generation failed.\nWeasyPrint error: {weasy_error}\nFallback error: {fb_err}"
        )